#!/usr/bin/env bash
set -euo pipefail
for tool in git unzip base64 sha256sum python3; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        printf '%s\n' 'ثبّت الأدوات أولاً: pkg install git unzip coreutils python'
        exit 1
    fi
done
STAGE_DIR=$(mktemp -d)
trap 'rm -rf "$STAGE_DIR"' EXIT
PAYLOAD_LINE=$(awk '/^__SOAPDIAG_PAYLOAD__$/ {print NR+1; exit}' "$0")
[ -n "$PAYLOAD_LINE" ] || { printf '%s\n' 'ERROR: حزمة SoapDiag غير مكتملة.'; exit 1; }
tail -n +"$PAYLOAD_LINE" "$0" | base64 -d > "$STAGE_DIR/source.zip"
printf '%s  %s\n' '4fd1accb8263732ff19092982f1ca93b383745c5644fb0517d957a0ff3eaecb0' "$STAGE_DIR/source.zip" | sha256sum --check --status || { printf '%s\n' 'ERROR: فشل فحص الحزمة.'; exit 1; }
unzip -q "$STAGE_DIR/source.zip" -d "$STAGE_DIR"
SOURCE_DIR="$STAGE_DIR/soapdiag-project"
printf '%s\n' 'SoapDiag 1.0 unpacked. Running source tests...'
python3 "$SOURCE_DIR/tests/test_source.py"
if [ "${SOAPDIAG_DRY_RUN:-0}" = '1' ]; then
    printf '%s\n' 'DRY RUN OK — لم يتم الاتصال بالمستودع.'
    exit 0
fi
BASE_REPO="${SOAPDIAG_BASE_REPO:-$HOME/studio-maestro}"
if [ ! -d "$BASE_REPO/.git" ]; then
    if [ -d "$HOME/StudioMaestro-e436b654/.git" ]; then BASE_REPO="$HOME/StudioMaestro-e436b654"; else
        printf '%s\n' "ERROR: لم أجد مستودع Git في $HOME/studio-maestro."
        exit 1
    fi
fi
REMOTE_NAME="${SOAPDIAG_REMOTE:-}"
if [ -n "$REMOTE_NAME" ]; then
    git -C "$BASE_REPO" remote get-url "$REMOTE_NAME" >/dev/null 2>&1 || { printf '%s\n' "ERROR: remote غير موجود: $REMOTE_NAME"; exit 1; }
elif git -C "$BASE_REPO" remote get-url gitlab >/dev/null 2>&1; then REMOTE_NAME='gitlab'
elif git -C "$BASE_REPO" remote get-url origin >/dev/null 2>&1; then REMOTE_NAME='origin'
else
    REMOTE_NAME=$(git -C "$BASE_REPO" remote | head -n 1 || true)
    [ -n "$REMOTE_NAME" ] || { printf '%s\n' 'ERROR: لا يوجد Git remote.'; exit 1; }
fi
REMOTE_URL=$(git -C "$BASE_REPO" remote get-url "$REMOTE_NAME")
WORK="$STAGE_DIR/repo"
mkdir -p "$WORK"
git -C "$WORK" init -q
git -C "$WORK" remote add upload "$REMOTE_URL"
git -C "$WORK" config user.name "SoapDiag Builder"
git -C "$WORK" config user.email "soapdiag@local.invalid"
printf '%s\n' "Using remote: $REMOTE_NAME"
printf '%s\n' 'الفرع المستهدف: soapdiag — فرع Studio Maestro الحالي لن يُلمس.'
if git -C "$WORK" ls-remote --exit-code --heads upload soapdiag >/dev/null 2>&1; then
    git -C "$WORK" fetch -q --depth=1 upload soapdiag
    git -C "$WORK" checkout -q -B soapdiag FETCH_HEAD
    git -C "$WORK" rm -rf . >/dev/null 2>&1 || true
else
    git -C "$WORK" checkout -q --orphan soapdiag
fi
cp -a "$SOURCE_DIR/." "$WORK/"
git -C "$WORK" add -A
git -C "$WORK" commit -q -m 'SoapDiag 1.0: independent player network diagnostics'
git -C "$WORK" push upload HEAD:soapdiag
printf '%s\n' 'تم رفع SoapDiag 1.0 على فرع soapdiag.'
printf '%s\n' 'GitLab: افتح Build > Pipelines ثم نزّل artifact باسم SoapDiag.'
printf '%s\n' 'GitHub: افتح Actions ثم Build SoapDiag APK ثم نزّل SoapDiag-1.0-apk.'
exit 0
